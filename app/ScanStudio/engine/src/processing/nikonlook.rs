//! Rust port of `negfit/nikonlook_core.py`'s frozen bundle API
//! (`load_bundle` / `estimate_gains` / `apply`) — the "Nikon Scan look"
//! color pipeline: a shared 3x3 matrix + per-channel monotone curve model
//! (Layer B, unchanged between bundle versions — v1's and v2's model.json
//! are byte-identical, only Layer A was retrained) plus a per-frame
//! exposure gain estimator (Layer A) implemented in exactly the two
//! versions `nikonlook_core.py::_validate_layer_a` (lines 349-447)
//! recognizes: `percentile-stopgap-v1` (a blind percentile-span ratio
//! against one anchor frame) and `hybrid-exposure-ridge-v2`
//! (`nikonlook_core.py` lines 512-680: an optional hardware-exposure
//! inverse when the caller supplies exposure metadata, otherwise a scored
//! blind ridge regression over 48 raw distribution features). `load_bundle`
//! rejects any other Layer A method or Layer B model type instead of
//! silently applying wrong math.
//!
//! `load_bundle()` parses the **v2** bundle — the production default: v2's
//! blind path measures materially closer to the registered Nikon Scan
//! reference than v1 on live frames (see
//! `resources/nikonlook-v2/PROVENANCE.md` for the measured numbers).
//! `load_bundle_v1()` parses the v1 bundle, kept for the existing pinned v1
//! tests (Groups A-G below) and comparison tooling. Both share
//! `parse_bundle`.
//!
//! Both bundles' JSON matrices/curves are vendored as compiled-in engine
//! resources under `engine/resources/nikonlook-v1/` and
//! `engine/resources/nikonlook-v2/`, embedded via `include_str!` — no
//! runtime file path, no network access. The numeric model targets Adobe
//! RGB-family encoded values, but ScanStudio does not redistribute or embed
//! a Nikon ICC profile. See each bundle directory's `PROVENANCE.md` for the
//! vendoring record and the owner's licensing grant citation.
//!
//! Every numeric literal in this module's v1 test suite (Groups A-G) was
//! generated by directly invoking the real `nikonlook_core.py` against the
//! real `nikonlook-v1` bundle (see plan 14-01's `<behavior>` block); the v2
//! test suite (Groups H-O) was generated the same way against the real
//! `nikonlook-v2` bundle. This is a faithful numeric port of a verified
//! reference implementation, not a reimplementation from first principles.

