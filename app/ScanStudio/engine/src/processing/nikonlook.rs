/// A loaded nikonlook bundle. Fields are private — only load_bundle /
/// estimate_gains / apply (this module's frozen API surface) touch them.
/// quality_tier/bundle_version are exposed for future provenance/debug/UI
/// use even though nothing calls them yet in this phase.
pub struct Bundle {
    matrix: [[f64; 3]; 3], // "M" from model.json, applied as-is (not transposed) — see algorithm note below
    curves: [MonotoneCurve; 3], // R, G, B order, from model.json's "curves"
    layer_a: LayerA,
    pub quality_tier: String,   // manifest.json "quality_tier"
    pub bundle_version: String, // manifest.json "bundle_version"
}

/// Layer A, dispatched by `layer_a.json`'s own `method` field (see this
/// module's doc comment). `estimate_gains` matches on this enum rather than
/// a stringly-typed method field, so an unsupported method can never reach
/// gain estimation — `parse_bundle` already rejects it before a `Bundle`
/// exists.
enum LayerA {
    V1(LayerAV1),
    V2(LayerAV2),
}

struct LayerAV1 {
    lo_pct: f64,
    hi_pct: f64,
    rail_lo_fraction: f64,
    rail_hi_fraction: f64,
    reference_lo: [f64; 3],
    reference_hi: [f64; 3],
    reference_k: [f64; 3],
    gain_bounds: (f64, f64),
}

/// v2's optional hardware-exposure inverse — mirrors `layer_a.json`'s
/// `metadata_estimator` object (`inverse-hardware-exposure-v1`).
struct MetadataEstimatorV1 {
    reference_exposure_10ns: [f64; 3],
    reference_gain: [f64; 3],
    gain_bounds: (f64, f64),
}

/// v2's scored blind fallback — mirrors `layer_a.json`'s `blind_fallback`
/// object (`log-ridge-raw-features-v1`): a standardized 48-feature
/// log-ridge regression to a per-channel log-gain.
struct BlindFallbackV1 {
    sample_stride: usize,
    rail_lo_fraction: f64,
    rail_hi_fraction: f64,
    feature_mean: Vec<f64>,
    feature_scale: Vec<f64>,
    log_gain_intercept: [f64; 3],
    coefficients: Vec<[f64; 3]>,
    gain_bounds: (f64, f64),
}

struct LayerAV2 {
    metadata: MetadataEstimatorV1,
    blind: BlindFallbackV1,
}

