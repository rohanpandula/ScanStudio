/// A loaded nikonlook bundle. Fields are private — only load_bundle /
/// estimate_gains / apply (this module's frozen API surface) touch them.
/// quality_tier/bundle_version are exposed for future provenance/debug/UI
/// use even though nothing calls them yet in this phase.
pub struct Bundle {
    matrix: [[f64; 3]; 3], // "M" from model.json, applied as-is (not transposed) — see algorithm note below
    curves: [MonotoneCurve; 3], // R, G, B order, from model.json's "curves"
    layer_a: LayerAV1,
    pub quality_tier: String,   // manifest.json "quality_tier"
    pub bundle_version: String, // manifest.json "bundle_version"
}

struct LayerAV1 {
    lo_pct: f64,
    hi_pct: f64,
    rail_lo_fraction: f64,
    rail_hi_fraction: f64,
    reference_lo: [f64; 3],
    reference_hi: [f64; 3],
    reference_k: [f64; 3],
    gain_bounds: (f64, f64),
}

// ---------------------------------------------------------------------
// Deserialization DTOs — only the fields this module actually reads.
// serde ignores the many other fields present in the real JSON
// automatically since none of these DTOs sets `deny_unknown_fields`.
// ---------------------------------------------------------------------

#[derive(Deserialize)]
struct ModelDto {
    model: String,
    #[serde(rename = "M")]
    m: Vec<Vec<f64>>,
    curves: Vec<CurveDto>,
}

#[derive(Deserialize)]
struct CurveDto {
    grid_x: Vec<f64>,
    grid_y: Vec<f64>,
    // Provenance-only in the Python source (see MonotoneCurve's doc
    // comment above) — deserialized to mirror the on-disk shape 1:1 but
    // deliberately never read past that.
    #[allow(dead_code)]
    decreasing: bool,
}

#[derive(Deserialize)]
struct LayerADto {
    method: String,
    lo_pct: f64,
    hi_pct: f64,
    rail_lo_fraction: f64,
    rail_hi_fraction: f64,
    gain_bounds: Vec<f64>,
    reference_lo: Vec<f64>,
    reference_hi: Vec<f64>,
    reference_k: Vec<f64>,
}

#[derive(Deserialize)]
struct ManifestDto {
    bundle_version: String,
    quality_tier: String,
    layer_a_method: Option<String>,
}

