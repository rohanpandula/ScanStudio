//! Rust port of `negfit/nikonlook_core.py`'s frozen bundle API
//! (`load_bundle` / `estimate_gains` / `apply`) — the "Nikon Scan look"
//! color pipeline: a 3x3 matrix + per-channel monotone curve model (Layer
//! B) plus a per-frame exposure gain estimator (Layer A) implementing
//! `nikonlook_core.py::_validate_layer_a`'s (lines 349-447)
//! `hybrid-exposure-ridge-v2` method (`nikonlook_core.py` lines 512-680: an
//! optional hardware-exposure inverse when the caller supplies exposure
//! metadata, otherwise a scored blind ridge regression over 48 raw
//! distribution features). `load_bundle` rejects any other Layer A method
//! or Layer B model type instead of silently applying wrong math.
//!
//! `percentile-stopgap-v1` — a blind percentile-span ratio against one
//! anchor frame, with no level anchor and no border exclusion — was this
//! model's first Layer A. It measured ΔE00 17-20 against the registered
//! Nikon Scan reference (see
//! `SCANSTUDIO-EXPOSURE-INVESTIGATION-qwen3.8-max-preview-20260728.md` in
//! the RE repo for the live-frame diagnosis) and was retired once v2
//! shipped; `load_bundle` no longer recognizes its method string at all,
//! the same as any other unsupported tag.
//!
//! The v2 bundle's JSON matrix/curves are vendored as compiled-in engine
//! resources under `engine/resources/nikonlook-v2/`, embedded via
//! `include_str!` — no runtime file path, no network access. The numeric
//! model targets Adobe RGB-family encoded values, but ScanStudio does not
//! redistribute or embed a Nikon ICC profile. See that directory's
//! `PROVENANCE.md` for the vendoring record and the owner's licensing
//! grant citation.
//!
//! Every numeric literal in this module's test suite was generated by
//! directly invoking the real `nikonlook_core.py` against the real bundle
//! under test (Groups A/I-O against `nikonlook-v2`; see plan 14-01's
//! `<behavior>` block). This is a faithful numeric port of a verified
//! reference implementation, not a reimplementation from first principles.

