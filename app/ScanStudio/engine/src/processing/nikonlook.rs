/// `u = M . z` — direct matrix-vector product (NOT transposed; see this
/// module's algorithm note in the plan's `<algorithm_notes>` point 1):
/// `u[j] = M[j][0]*z[0] + M[j][1]*z[1] + M[j][2]*z[2]`.
fn matmul3(m: &[[f64; 3]; 3], z: [f64; 3]) -> [f64; 3] {
    [
        m[0][0] * z[0] + m[0][1] * z[1] + m[0][2] * z[2],
        m[1][0] * z[0] + m[1][1] * z[1] + m[1][2] * z[2],
        m[2][0] * z[0] + m[2][1] * z[1] + m[2][2] * z[2],
    ]
}

/// Layer B: nikon_c = curves[c]((raw * k) @ M)_c, clipped to [0,1]. Returns
/// the same length as `raw`. See algorithm note above for the exact matrix
/// orientation (M applied directly, not transposed).
pub fn apply(raw: &[[f64; 3]], k: [f64; 3], bundle: &Bundle) -> Vec<[f64; 3]> {
    raw.iter()
        .map(|px| {
            let z = [px[0] * k[0], px[1] * k[1], px[2] * k[2]];
            let u = matmul3(&bundle.matrix, z);
            [
                bundle.curves[0].apply(u[0]).clamp(0.0, 1.0),
                bundle.curves[1].apply(u[1]).clamp(0.0, 1.0),
                bundle.curves[2].apply(u[2]).clamp(0.0, 1.0),
            ]
        })
        .collect()
}

