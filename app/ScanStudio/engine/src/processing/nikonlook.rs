/// Mirrors `app/ScanStudio/engine/src/parity/types.rs`'s `ParityError`
/// shape. No `Io` variant — this module never touches the filesystem at
/// runtime (bundle data is compiled in via `include_str!`).
#[derive(Debug)]
pub enum NikonlookError {
    Json(serde_json::Error),
    Invalid(String),
}

impl std::fmt::Display for NikonlookError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            NikonlookError::Json(err) => write!(f, "json error: {err}"),
            NikonlookError::Invalid(message) => write!(f, "invalid nikonlook bundle: {message}"),
        }
    }
}

impl std::error::Error for NikonlookError {}

impl From<serde_json::Error> for NikonlookError {
    fn from(err: serde_json::Error) -> Self {
        NikonlookError::Json(err)
    }
}

