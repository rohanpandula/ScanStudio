/// Returns true only for a complete, finite, strictly-positive hardware
/// exposure triple. Invalid metadata is routed to the blind estimator.
pub fn exposure_is_usable(exposure_10ns: [f64; 3]) -> bool {
    exposure_10ns
        .iter()
        .all(|&value| value.is_finite() && value > 0.0)
}

/// Per-frame exposure gain estimate ("Layer A"). `raw` is scanner-linear
/// RGB in [0,1] (16-bit raw counts / 65535), one [R,G,B] triple per pixel,
/// row-major, `width` wide (height is inferred as `raw.len() / width`).
///
/// `exposure_10ns` is the caller's per-channel hardware exposure duration
/// in 10ns ticks (mirrors nikonlook_core.py's `meta["exposure_10ns"]`),
/// `None` when unavailable. Used when present (the
/// `inverse-hardware-exposure-v1` path — the caller must guarantee each
/// component is finite and > 0; only `debug_assert!`-checked, since this is
/// a hot per-frame call and the bundle's own gain_bounds clamp already
/// contains a bad ratio's blast radius); otherwise falls back to
/// `log-ridge-raw-features-v1`, the scored blind estimator, which is the
/// only path that can return `Err` (a degenerate `raw`/`width` pairing —
/// see `layer_a_v2_features` — unreachable for real engine data, which is
/// always an exact (H,W,3) raster).
///
/// Returns (3,) gain, clamped to the active method's own gain_bounds.
pub fn estimate_gains(
    raw: &[[f64; 3]],
    width: usize,
    exposure_10ns: Option<[f64; 3]>,
    bundle: &Bundle,
) -> Result<[f64; 3], NikonlookError> {
    let la = &bundle.layer_a;
    if let Some(exposure) = exposure_10ns.filter(|&value| exposure_is_usable(value)) {
        let mut gain = [0.0f64; 3];
        for c in 0..3 {
            gain[c] = la.metadata.reference_gain[c] * la.metadata.reference_exposure_10ns[c]
                / exposure[c];
        }
        let (lo_bound, hi_bound) = la.metadata.gain_bounds;
        for value in gain.iter_mut() {
            *value = value.clamp(lo_bound, hi_bound);
        }
        Ok(gain)
    } else {
        let features = layer_a_v2_features(raw, width, &la.blind)?;
        let mut standardized = [0.0f64; 48];
        for i in 0..48 {
            standardized[i] = (features[i] - la.blind.feature_mean[i]) / la.blind.feature_scale[i];
        }
        let mut gain = [0.0f64; 3];
        for c in 0..3 {
            let mut sum = la.blind.log_gain_intercept[c];
            for (i, value) in standardized.iter().enumerate() {
                sum += value * la.blind.coefficients[i][c];
            }
            gain[c] = sum.exp();
        }
        let (lo_bound, hi_bound) = la.blind.gain_bounds;
        for value in gain.iter_mut() {
            *value = value.clamp(lo_bound, hi_bound);
        }
        Ok(gain)
    }
}

// ---------------------------------------------------------------------
// Layer B -- apply
// ---------------------------------------------------------------------

/// `u = M . z` — direct matrix-vector product (NOT transposed; see this
/// module's algorithm note in the plan's `<algorithm_notes>` point 1):
/// `u[j] = M[j][0]*z[0] + M[j][1]*z[1] + M[j][2]*z[2]`.
fn matmul3(m: &[[f64; 3]; 3], z: [f64; 3]) -> [f64; 3] {
    [
        m[0][0] * z[0] + m[0][1] * z[1] + m[0][2] * z[2],
        m[1][0] * z[0] + m[1][1] * z[1] + m[1][2] * z[2],
        m[2][0] * z[0] + m[2][1] * z[1] + m[2][2] * z[2],
    ]
}

/// Layer B: nikon_c = curves[c]((raw * k) @ M)_c, clipped to [0,1]. Returns
/// the same length as `raw`. See algorithm note above for the exact matrix
/// orientation (M applied directly, not transposed).
pub fn apply(raw: &[[f64; 3]], k: [f64; 3], bundle: &Bundle) -> Vec<[f64; 3]> {
    raw.iter()
        .map(|px| {
            let z = [px[0] * k[0], px[1] * k[1], px[2] * k[2]];
            let u = matmul3(&bundle.matrix, z);
            [
                bundle.curves[0].apply(u[0]).clamp(0.0, 1.0),
                bundle.curves[1].apply(u[1]).clamp(0.0, 1.0),
                bundle.curves[2].apply(u[2]).clamp(0.0, 1.0),
            ]
        })
        .collect()
}

