const MODEL_JSON: &str = include_str!("../../resources/nikonlook-v1/model.json");
const LAYER_A_JSON: &str = include_str!("../../resources/nikonlook-v1/layer_a.json");
const MANIFEST_JSON: &str = include_str!("../../resources/nikonlook-v1/manifest.json");

/// Parses the three embedded JSON strings (model.json, layer_a.json,
/// manifest.json) via include_str!. No file path parameter — this port only
/// ever loads the one vendored numeric bundle. Returns
/// NikonlookError::Invalid (not a panic) if
/// model.json's "model" field != "DirectPF", or layer_a.json's "method"
/// field != "percentile-stopgap-v1" (this port implements ONLY the v1
/// percentile-stopgap method — the only method the nikonlook-v1 bundle
/// uses; any other method fails loudly here, exactly mirroring
/// nikonlook_core.py's own _validate_layer_a/estimate_gains guard behavior
/// for unsupported methods, never silently applying wrong math).
pub fn load_bundle() -> Result<Bundle, NikonlookError> {
    parse_bundle(MODEL_JSON, LAYER_A_JSON, MANIFEST_JSON)
}

/// Internal parse/validate helper shared by `load_bundle` (real embedded
/// data) and this module's own tests (hand-built malformed JSON strings) —
/// see the Group G tests below.
fn parse_bundle(
    model_json: &str,
    layer_a_json: &str,
    manifest_json: &str,
) -> Result<Bundle, NikonlookError> {
    let model: ModelDto = serde_json::from_str(model_json)?;
    let layer_a: LayerADto = serde_json::from_str(layer_a_json)?;
    let manifest: ManifestDto = serde_json::from_str(manifest_json)?;

    if model.model != "DirectPF" {
        return Err(NikonlookError::Invalid(format!(
            "model.json: unrecognized Layer B model type {:?} — this port only applies \
             DirectPF-format models (fit37/model_directpf.py's serialization)",
            model.model
        )));
    }
    if layer_a.method != "percentile-stopgap-v1" {
        return Err(NikonlookError::Invalid(format!(
            "layer_a.json: unsupported Layer-A method {:?} — this port implements only \
             percentile-stopgap-v1",
            layer_a.method
        )));
    }
    if let Some(manifest_method) = &manifest.layer_a_method {
        if manifest_method != &layer_a.method {
            return Err(NikonlookError::Invalid(format!(
                "manifest layer_a_method {manifest_method:?} does not match layer_a.json \
                 method {:?}",
                layer_a.method
            )));
        }
    }

    if model.m.len() != 3 || !model.m.iter().all(|row| row.len() == 3) {
        return Err(NikonlookError::Invalid(format!(
            "model.json: expected a 3x3 'M' matrix, got {} row(s)",
            model.m.len()
        )));
    }
    let mut matrix = [[0.0f64; 3]; 3];
    for (i, row) in model.m.iter().enumerate() {
        matrix[i] = [row[0], row[1], row[2]];
    }

    if model.curves.len() != 3 {
        return Err(NikonlookError::Invalid(format!(
            "model.json: expected exactly 3 curves (R,G,B), got {}",
            model.curves.len()
        )));
    }
    let curves_vec: Vec<MonotoneCurve> = model
        .curves
        .into_iter()
        .map(|curve| MonotoneCurve {
            grid_x: curve.grid_x,
            grid_y: curve.grid_y,
        })
        .collect();
    let curves: [MonotoneCurve; 3] = curves_vec
        .try_into()
        .map_err(|_| NikonlookError::Invalid("model.json: expected exactly 3 curves (R,G,B)".to_string()))?;

    let reference_lo = fixed3(&layer_a.reference_lo, "layer_a.json:reference_lo")?;
    let reference_hi = fixed3(&layer_a.reference_hi, "layer_a.json:reference_hi")?;
    let reference_k = fixed3(&layer_a.reference_k, "layer_a.json:reference_k")?;
    let gain_bounds = fixed2(&layer_a.gain_bounds, "layer_a.json:gain_bounds")?;

    let layer_a_v1 = LayerAV1 {
        lo_pct: layer_a.lo_pct,
        hi_pct: layer_a.hi_pct,
        rail_lo_fraction: layer_a.rail_lo_fraction,
        rail_hi_fraction: layer_a.rail_hi_fraction,
        reference_lo,
        reference_hi,
        reference_k,
        gain_bounds: (gain_bounds[0], gain_bounds[1]),
    };

    Ok(Bundle {
        matrix,
        curves,
        layer_a: layer_a_v1,
        quality_tier: manifest.quality_tier,
        bundle_version: manifest.bundle_version,
    })
}

/// Validates a field's value slice has exactly 3 elements, converting into
/// a fixed-size array — `NikonlookError::Invalid` with a clear message
/// (naming the field) on any shape mismatch.
fn fixed3(values: &[f64], field: &str) -> Result<[f64; 3], NikonlookError> {
    if values.len() != 3 {
        return Err(NikonlookError::Invalid(format!(
            "{field}: expected 3 values, got {}",
            values.len()
        )));
    }
    Ok([values[0], values[1], values[2]])
}

/// Same as `fixed3` but for 2-element fields (e.g. `gain_bounds`).
fn fixed2(values: &[f64], field: &str) -> Result<[f64; 2], NikonlookError> {
    if values.len() != 2 {
        return Err(NikonlookError::Invalid(format!(
            "{field}: expected 2 values, got {}",
            values.len()
        )));
    }
    Ok([values[0], values[1]])
}

// ---------------------------------------------------------------------
// Percentile primitive (mirrors nikonlook_core.py's unclipped_percentiles)
// ---------------------------------------------------------------------

/// NumPy's default "linear" percentile interpolation on an ALREADY SORTED
/// ascending slice. `p` is in [0, 100].
fn percentile_linear(sorted: &[f64], p: f64) -> f64 {
    let n = sorted.len();
    debug_assert!(n > 0, "percentile_linear requires a non-empty slice");
    if n == 1 {
        return sorted[0];
    }
    let idx = (p / 100.0) * (n - 1) as f64;
    let lo_idx = idx.floor() as usize;
    let hi_idx = idx.ceil() as usize;
    if lo_idx == hi_idx {
        return sorted[lo_idx];
    }
    let frac = idx - lo_idx as f64;
    sorted[lo_idx] * (1.0 - frac) + sorted[hi_idx] * frac
}

/// Per-channel [lo_pct, hi_pct] percentile of a single-channel raw-linear
/// slice, excluding samples at/near the sensor rails (<= rail_lo_fraction
/// or >= rail_hi_fraction), so a handful of blown highlights or a
/// near-black border don't skew the anchor points. Falls back to the
/// unmasked population if fewer than 1000 unclipped samples remain (uses
/// the ENTIRE original slice in that case, not the small filtered subset).
fn unclipped_percentiles(
    channel: &[f64],
    lo_pct: f64,
    hi_pct: f64,
    rail_lo_fraction: f64,
    rail_hi_fraction: f64,
) -> (f64, f64) {
    let masked: Vec<f64> = channel
        .iter()
        .copied()
        .filter(|&v| v > rail_lo_fraction && v < rail_hi_fraction)
        .collect();
    let mut vals = if masked.len() >= 1000 { masked } else { channel.to_vec() };
    // f64::total_cmp, not partial_cmp().unwrap(), so a stray NaN cannot
    // panic the sort.
    vals.sort_by(f64::total_cmp);
    let lo = percentile_linear(&vals, lo_pct);
    let hi = percentile_linear(&vals, hi_pct);
    (lo, hi)
}

// ---------------------------------------------------------------------
// Layer A -- estimate_gains (percentile-stopgap-v1 only)
// ---------------------------------------------------------------------

/// Per-frame exposure gain estimate ("Layer A", percentile-stopgap-v1 only
/// — see load_bundle's method guard). `raw` is scanner-linear RGB in
/// [0,1] (16-bit raw counts / 65535), one [R,G,B] triple per pixel,
/// row-major, any length. Returns (3,) gain, clamped to
/// bundle.layer_a.gain_bounds. Omits the `meta` parameter present in
/// nikonlook_core.py's signature: v1 ignores meta unconditionally per the
/// frozen API's own documented behavior, and load_bundle rejects any
/// non-v1 method before this function could ever need it.
pub fn estimate_gains(raw: &[[f64; 3]], bundle: &Bundle) -> [f64; 3] {
    let la = &bundle.layer_a;
    let mut k = [0.0f64; 3];
    for c in 0..3 {
        let channel: Vec<f64> = raw.iter().map(|px| px[c]).collect();
        let (in_lo, in_hi) = unclipped_percentiles(
            &channel,
            la.lo_pct,
            la.hi_pct,
            la.rail_lo_fraction,
            la.rail_hi_fraction,
        );
        let in_span = (in_hi - in_lo).max(1e-9);
        let ref_span = (la.reference_hi[c] - la.reference_lo[c]).max(1e-9);
        k[c] = la.reference_k[c] * (ref_span / in_span);
    }
    let (lo_bound, hi_bound) = la.gain_bounds;
    for value in k.iter_mut() {
        *value = value.clamp(lo_bound, hi_bound);
    }
    k
}

// ---------------------------------------------------------------------
// Layer B -- apply
// ---------------------------------------------------------------------

/// `u = M . z` — direct matrix-vector product (NOT transposed; see this
/// module's algorithm note in the plan's `<algorithm_notes>` point 1):
/// `u[j] = M[j][0]*z[0] + M[j][1]*z[1] + M[j][2]*z[2]`.
fn matmul3(m: &[[f64; 3]; 3], z: [f64; 3]) -> [f64; 3] {
    [
        m[0][0] * z[0] + m[0][1] * z[1] + m[0][2] * z[2],
        m[1][0] * z[0] + m[1][1] * z[1] + m[1][2] * z[2],
        m[2][0] * z[0] + m[2][1] * z[1] + m[2][2] * z[2],
    ]
}

/// Layer B: nikon_c = curves[c]((raw * k) @ M)_c, clipped to [0,1]. Returns
/// the same length as `raw`. See algorithm note above for the exact matrix
/// orientation (M applied directly, not transposed).
pub fn apply(raw: &[[f64; 3]], k: [f64; 3], bundle: &Bundle) -> Vec<[f64; 3]> {
    raw.iter()
        .map(|px| {
            let z = [px[0] * k[0], px[1] * k[1], px[2] * k[2]];
            let u = matmul3(&bundle.matrix, z);
            [
                bundle.curves[0].apply(u[0]).clamp(0.0, 1.0),
                bundle.curves[1].apply(u[1]).clamp(0.0, 1.0),
                bundle.curves[2].apply(u[2]).clamp(0.0, 1.0),
            ]
        })
        .collect()
}

