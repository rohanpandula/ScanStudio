/// Runtime feature extraction for v2's blind fallback — mirrors
/// `nikonlook_core.py::_layer_a_v2_features` for the (H,W,3) input case
/// only (the engine never calls this with a flat (N,3) list; Python's
/// `_as_rows`-style (N,3) branch has no equivalent here).
///
/// `raw.len()` must be an exact multiple of `width` — engine data always is
/// (every raw buffer this module receives is a decoded (H,W,3) raster
/// flattened row-major); failing loudly on a mismatch matches the Python
/// reshape contract (`raw.reshape(-1, 3)` on a non-rectangular array raises
/// too) rather than silently misinterpreting the buffer.
fn layer_a_v2_features(
    raw: &[[f64; 3]],
    width: usize,
    blind: &BlindFallbackV1,
) -> Result<[f64; 48], NikonlookError> {
    if width == 0 || raw.len() % width != 0 {
        return Err(NikonlookError::Invalid(format!(
            "layer_a_v2_features: raw length {} is not an exact multiple of width {width}",
            raw.len()
        )));
    }
    let height = raw.len() / width;
    let stride = blind.sample_stride;

    let mut values: Vec<f64> = Vec::with_capacity(LAYER_A_V2_FEATURE_COUNT);
    for c in 0..3 {
        // Row-major sampled order, identical to NumPy's `raw[::s, ::s, :]`
        // (y outer, x inner, both ascending).
        let mut channel: Vec<f64> = Vec::new();
        for y in (0..height).step_by(stride) {
            for x in (0..width).step_by(stride) {
                let value = raw[y * width + x][c];
                if value.is_finite() {
                    channel.push(value);
                }
            }
        }
        if channel.is_empty() {
            return Err(NikonlookError::Invalid(format!(
                "layer_a_v2_features: raw channel {} has no finite samples",
                ['R', 'G', 'B'][c]
            )));
        }

        let masked: Vec<f64> = channel
            .iter()
            .copied()
            .filter(|&v| v > blind.rail_lo_fraction && v < blind.rail_hi_fraction)
            .collect();
        let mut population = if masked.len() >= 1000 {
            masked
        } else {
            channel
        };
        // f64::total_cmp, not partial_cmp().unwrap(), so a stray NaN cannot
        // panic the sort.
        population.sort_by(f64::total_cmp);

        // One sort, 13 percentile_linear lookups on the same sorted slice.
        let quantiles: Vec<f64> = LAYER_A_V2_QUANTILES
            .iter()
            .map(|&p| percentile_linear(&population, p))
            .collect();
        values.extend_from_slice(&quantiles);
        // Spans BEFORE log: q[12]-q[0], q[11]-q[1], q[10]-q[2].
        for &(lo, hi) in LAYER_A_V2_SPAN_INDEX_PAIRS.iter() {
            values.push(quantiles[hi] - quantiles[lo]);
        }
    }
    debug_assert_eq!(values.len(), LAYER_A_V2_FEATURE_COUNT);

    let mut features = [0.0f64; 48];
    for (i, &v) in values.iter().enumerate() {
        features[i] = v.max(1e-9).ln();
    }
    Ok(features)
}

