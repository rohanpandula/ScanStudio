// v2 field validation — mirrors nikonlook_core.py's `_finite_array` /
// `_finite_scalar` / `_validated_gain_bounds` (lines 308-328), used only by
// the v2 branch. v1's `fixed3`/`fixed2` above predate this and are left as
// they are — the existing v1 tests must keep passing unchanged.
