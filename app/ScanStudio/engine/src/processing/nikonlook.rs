/// One Layer-B monotone curve (R, G, or B). `.apply(x)` must match NumPy's
/// `np.interp(x, grid_x, grid_y)` exactly: grid_x is sorted ascending
/// (verified: 257 points in the bundle, strictly increasing).
/// If x <= grid_x[0], return grid_y[0]. If x >= grid_x[last], return
/// grid_y[last]. Otherwise linearly interpolate between the two bracketing
/// grid points. (`decreasing` from the Python source is provenance-only and
/// is never read by `.apply()` — confirmed by reading nikonlook_core.py's
/// `MonotoneCurveLite.apply`, which always does `np.interp(x, grid_x,
/// grid_y)` regardless of the `decreasing` flag — so this port omits the
/// field from this struct entirely.)
pub struct MonotoneCurve {
    pub grid_x: Vec<f64>,
    pub grid_y: Vec<f64>,
}

impl MonotoneCurve {
    pub fn apply(&self, x: f64) -> f64 {
        let n = self.grid_x.len();
        debug_assert!(n > 0, "MonotoneCurve grid must be non-empty");
        if n == 1 {
            return self.grid_y[0];
        }
        // IEEE 754: every comparison against NaN is false, never true, so a
        // NaN x falls through both the low- and high-end clamps below
        // untouched, then through partition_point's `gx <= x` predicate --
        // false for every element, since NaN can't satisfy `<=` either --
        // leaving `hi == 0` and the following `hi - 1` to underflow
        // (`usize`, panics in debug; wraps to an out-of-bounds index and
        // panics on the array read in release). This is not a hypothetical
        // input: `x` here is a real decoded pixel value (nikonlook::apply
        // feeds raw scanner data straight into this function with no
        // upstream finite check), and a dead sensor site or an upstream
        // divide-by-zero can genuinely produce one. This input shape is
        // outside what the numpy-parity fixtures this struct's docstring
        // claims exactness against exercise, so instead of inheriting
        // whatever np.interp happens to do with it, this port picks
        // deterministically: route it to the same floor output an
        // out-of-range-low x already gets, since "clamp to the curve's
        // lowest defined output" is the one answer that is both
        // non-panicking and consistent with every other out-of-domain input
        // this function already handles.
        if x.is_nan() {
            return self.grid_y[0];
        }
        if x <= self.grid_x[0] {
            return self.grid_y[0];
        }
        if x >= self.grid_x[n - 1] {
            return self.grid_y[n - 1];
        }
        // First index where grid_x[i] > x. Since grid_x is strictly
        // ascending and grid_x[0] < x < grid_x[n-1] here, `hi` is in
        // 1..=(n-1) — matches NumPy's np.interp bracketing for a strictly
        // increasing grid, including the exact-grid-point case (frac = 0).
        let hi = self.grid_x.partition_point(|&gx| gx <= x);
        let lo = hi - 1;
        let x0 = self.grid_x[lo];
        let x1 = self.grid_x[hi];
        let y0 = self.grid_y[lo];
        let y1 = self.grid_y[hi];
        let span = x1 - x0;
        if span <= 0.0 {
            // Degenerate/duplicate grid_x — not expected in the real
            // bundle (verified strictly increasing), but np.interp
            // returns the right-hand sample in this case.
            return y1;
        }
        let frac = (x - x0) / span;
        y0 + (y1 - y0) * frac
    }
}

