/// Parses the three embedded v2 JSON strings (model.json, layer_a.json,
/// manifest.json) via include_str! — this is the production default: v2's
/// blind path measures materially closer to the registered Nikon Scan
/// reference than v1 on live frames (see
/// `resources/nikonlook-v2/PROVENANCE.md` for the measured numbers).
/// Returns `NikonlookError::Invalid` (not a panic) on a malformed bundle —
/// see `parse_bundle`.
pub fn load_bundle() -> Result<Bundle, NikonlookError> {
    parse_bundle(MODEL_JSON_V2, LAYER_A_JSON_V2, MANIFEST_JSON_V2)
}

/// Parses the three embedded v1 JSON strings. Kept for the existing pinned
/// v1 tests (Groups A-G below) and any comparison tooling that still wants
/// the original `percentile-stopgap-v1` estimator; not the production
/// default — see `load_bundle`.
pub fn load_bundle_v1() -> Result<Bundle, NikonlookError> {
    parse_bundle(MODEL_JSON_V1, LAYER_A_JSON_V1, MANIFEST_JSON_V1)
}

/// Internal parse/validate helper shared by `load_bundle` / `load_bundle_v1`
/// (real embedded data) and this module's own tests (hand-built malformed
/// JSON strings) — see the Group G/O tests below. Dispatches on
/// `layer_a.json`'s own `method` field: returns `NikonlookError::Invalid`
/// (not a panic) if model.json's "model" field != "DirectPF", if the method
/// names neither supported Layer-A version, or if the manifest's
/// `layer_a_method` (when present) disagrees with layer_a.json's own method
/// — mirroring `nikonlook_core.py::_validate_layer_a`'s guard behavior for
/// unsupported or inconsistent bundles, never silently applying wrong math.
fn parse_bundle(
    model_json: &str,
    layer_a_json: &str,
    manifest_json: &str,
) -> Result<Bundle, NikonlookError> {
    let model: ModelDto = serde_json::from_str(model_json)?;
    let method_probe: LayerAMethodProbeDto = serde_json::from_str(layer_a_json)?;
    let manifest: ManifestDto = serde_json::from_str(manifest_json)?;
    let method = method_probe.method;

    if model.model != "DirectPF" {
        return Err(NikonlookError::Invalid(format!(
            "model.json: unrecognized Layer B model type {:?} — this port only applies \
             DirectPF-format models (fit37/model_directpf.py's serialization)",
            model.model
        )));
    }
    if method != LAYER_A_V1_METHOD && method != LAYER_A_V2_METHOD {
        return Err(NikonlookError::Invalid(format!(
            "layer_a.json: unsupported Layer-A method {method:?} — supported methods are \
             {LAYER_A_V1_METHOD:?} and {LAYER_A_V2_METHOD:?}"
        )));
    }
    if let Some(manifest_method) = &manifest.layer_a_method {
        if manifest_method != &method {
            return Err(NikonlookError::Invalid(format!(
                "manifest layer_a_method {manifest_method:?} does not match layer_a.json \
                 method {method:?}"
            )));
        }
    }

    if model.m.len() != 3 || !model.m.iter().all(|row| row.len() == 3) {
        return Err(NikonlookError::Invalid(format!(
            "model.json: expected a 3x3 'M' matrix, got {} row(s)",
            model.m.len()
        )));
    }
    let mut matrix = [[0.0f64; 3]; 3];
    for (i, row) in model.m.iter().enumerate() {
        matrix[i] = [row[0], row[1], row[2]];
    }

    if model.curves.len() != 3 {
        return Err(NikonlookError::Invalid(format!(
            "model.json: expected exactly 3 curves (R,G,B), got {}",
            model.curves.len()
        )));
    }
    let curves_vec: Vec<MonotoneCurve> = model
        .curves
        .into_iter()
        .map(|curve| MonotoneCurve {
            grid_x: curve.grid_x,
            grid_y: curve.grid_y,
        })
        .collect();
    let curves: [MonotoneCurve; 3] = curves_vec
        .try_into()
        .map_err(|_| NikonlookError::Invalid("model.json: expected exactly 3 curves (R,G,B)".to_string()))?;

    let layer_a = if method == LAYER_A_V1_METHOD {
        let layer_a_dto: LayerADto = serde_json::from_str(layer_a_json)?;
        LayerA::V1(build_layer_a_v1(layer_a_dto)?)
    } else {
        let layer_a_dto: LayerAV2Dto = serde_json::from_str(layer_a_json)?;
        LayerA::V2(build_layer_a_v2(layer_a_dto)?)
    };

    Ok(Bundle {
        matrix,
        curves,
        layer_a,
        quality_tier: manifest.quality_tier,
        bundle_version: manifest.bundle_version,
    })
}

